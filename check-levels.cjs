const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const source = fs.readFileSync('levels.js', 'utf8');
const levels = vm.runInNewContext(`${source}; CORE_LEVELS`);
const rules = require('./puzzle-rules.js');
const {solve} = require('./puzzle-solver.js');

const results=[];
assert.equal(levels.length,106);
for (const [index,level] of levels.entries()) {
  assert.equal(level.start.length,level.target.length);
  const width=level.start[0].length;
  assert(width>0);
  assert([...level.start,...level.target].every(row=>row.length===width),`Rectangular level ${index+1}`);
  assert.match(level.start.join(''), /^[RBGYWP.]+$/);
  assert.match(level.target.join(''), /^[RBGYWP.]+$/);
  assert.equal([...level.start.join('')].sort().join(''),[...level.target.join('')].sort().join(''));
  assert.deepEqual([...level.start.join('')].map((t,i)=>t==='.'?i:null).filter(i=>i!==null),[...level.target.join('')].map((t,i)=>t==='.'?i:null).filter(i=>i!==null));
  const result=solve(level);
  if (process.argv.includes('--update')) {
    level.par = result.distance;
    level.solution_len = result.distance;
    const identities=Array.from({length:level.start.length*width},(_,i)=>i);
    const needed=identities.map(()=>0);
    for(const [from,to] of result.path) {
      needed[identities[from]]++;
      [identities[from],identities[to]]=[identities[to],identities[from]];
    }
    assert(needed.every(n=>n<=6),'Verified route fits 3–6 allowances');
    level.allowanceFloor=level.start.map((row,r)=>[...row].map((t,c)=>needed[r*width+c]));
  }
  assert.equal(result.distance,level.par,`Optimal par for level ${index+1}`);
  assert.equal(result.distance,level.solution_len);
  assert(level.allowanceFloor.every((row,r)=>row.length===width&&row.every((n,c)=>Number.isInteger(n)&&n>=0&&n<=6&&((level.start[r][c]!=='.'&&level.start[r][c]!=='W')||n===0))));
  let board=rules.parse(level.start);
  let remaining=level.start.map((row,r)=>[...row].map((t,c)=>t==='.'||t==='W'?0:Math.max(3,level.allowanceFloor[r][c])));
  for(const [from,to] of result.path) {
    const a=[Math.floor(from/width),from%width], b=[Math.floor(to/width),to%width];
    assert(rules.legalMoves(board,...a).some(([r,c])=>r===b[0]&&c===b[1]));
    assert(rules.legalMoves(board,...a,remaining).some(([r,c])=>r===b[0]&&c===b[1]));
    remaining[a[0]][a[1]]--;
    remaining=rules.swapCells(remaining,a,b);
    board=rules.swapCells(board,a,b);
  }
  assert.equal(rules.key(board),rules.key(rules.parse(level.target)));
  console.log(`${index+1}: ${result.distance} moves (par ${level.par}) ${level.name}`);
  results.push({level:index+1,name:level.name,world:level.world,par:level.par,width,...result});
}
fs.writeFileSync('level-checks.json', JSON.stringify(results,null,2)+'\n');
fs.writeFileSync('level-solutions.js','// Generated by check-levels.cjs from verified optimal routes. Stable level positions.\nconst LEVEL_SOLUTIONS = '+JSON.stringify(results.map(result=>result.path))+';\n');
if (process.argv.includes('--update')) fs.writeFileSync('levels.js','// Stable array positions preserve saved progress.\nconst CORE_LEVELS = '+JSON.stringify(levels,null,2)+';\n');
console.log(`All ${levels.length} levels solved; shortest paths written to level-checks.json.`);
