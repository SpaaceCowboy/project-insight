// Builds the username word lists the server and the app share.
//   node tools/build-username-words.mjs
// Sources: tools/ldnoobw-en.txt (the LDNOOBW English list, CC BY 4.0, https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words),
// the older world-name list app/src/main/assets/blocked-words.json, and the reviewed additions in tools/username-words-extra.json.
// Output: app/src/main/assets/username-words.json and server/src/username-words.ts (identical content; server/test/username.test.ts fails if they differ).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFileSync(join(root, file), 'utf8');
const extra = JSON.parse(read('tools/username-words-extra.json'));
const legacy = JSON.parse(read('app/src/main/assets/blocked-words.json'));
const ldnoobw = read('tools/ldnoobw-en.txt').split(/\r?\n/u);

// Stored lower-case with spaces and punctuation removed: the filter compares words with the same separators removed.
const key = word => word.toLowerCase().normalize('NFKD').replace(/[^a-z0-9]/gu, '');
const CATEGORIES = ['hate', 'violence', 'profanity', 'reserved'];
const sets = Object.fromEntries(CATEGORIES.map(c => [c, { exact: new Set(), contains: new Set() }]));
for (const category of CATEGORIES) {
  for (const w of extra[category]?.exact ?? []) if (key(w)) sets[category].exact.add(key(w));
  for (const w of extra[category]?.contains ?? []) if (key(w)) sets[category].contains.add(key(w));
}
// Everything else in the older lists and LDNOOBW is profanity unless a reviewed list above already placed it.
const placed = new Set(CATEGORIES.flatMap(c => [...sets[c].exact, ...sets[c].contains]));
for (const w of [...ldnoobw, ...legacy.exact]) { const k = key(w); if (k.length >= 2 && !placed.has(k)) { sets.profanity.exact.add(k); placed.add(k); } }
for (const w of legacy.contains) { const k = key(w); if (k.length >= 4 && !placed.has(k) && k !== 'sexual') { sets.profanity.contains.add(k); placed.add(k); } }
// "sexual" is only unsafe as a whole word ("bisexual" must stay usable).
sets.profanity.exact.add('sexual'); sets.profanity.contains.delete('sexual');

const out = {};
for (const category of CATEGORIES) {
  const { exact, contains } = sets[category];
  for (const root of contains) if (root.length < 4) throw new Error(`${category}: root "${root}" is too short to match inside words`);
  // A root is also kept as a whole word: that is how a spaced phrase ("white power") is matched when its words are joined.
  const exactList = [...exact].sort();
  out[category] = { exact: exactList, contains: [...contains].sort() };
}
// Hate beats violence beats profanity: a word listed in a stronger category is removed from the weaker ones.
for (let i = 0; i < CATEGORIES.length - 1; i++) for (let j = i + 1; j < CATEGORIES.length - 1; j++) {
  for (const kind of ['exact', 'contains']) out[CATEGORIES[j]][kind] = out[CATEGORIES[j]][kind].filter(w => !out[CATEGORIES[i]].exact.includes(w) && !out[CATEGORIES[i]].contains.includes(w));
}

const json = JSON.stringify(out, null, 2) + '\n';
writeFileSync(join(root, 'app/src/main/assets/username-words.json'), json);
writeFileSync(join(root, 'server/src/username-words.ts'),
  '// Generated by tools/build-username-words.mjs from LDNOOBW (CC BY 4.0) plus reviewed additions. Mirrors app/src/main/assets/username-words.json.\n' +
  `export const usernameWords = ${json.trimEnd()} as const;\n`);
console.log(CATEGORIES.map(c => `${c}: ${out[c].exact.length} exact, ${out[c].contains.length} contains`).join('; '));
